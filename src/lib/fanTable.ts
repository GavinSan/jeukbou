// 番數表：每個牌友圈一份，預設來自「台灣牌計番表」Google Sheet，局主可改。
// 每項 value 用簡單寫法：「5」、「明:5|暗:15」、「刻:5|順:3」；# 後面係備註。

export interface FanItem {
  name: string;
  /** 「5」或者「明:5|暗:15」 */
  value: string;
  note?: string;
}

export interface FanSection {
  title: string;
  /** pick = 入番數時可以撳嚟加；info = 只係參考（例如自動計、即時找數） */
  kind: 'pick' | 'info';
  items: FanItem[];
}

export interface FanTable {
  sections: FanSection[];
  /** 牌例 / 規矩（文字） */
  rules: string[];
}

export interface FanOption {
  label: string;
  fan: number;
}

/** 「明:5|暗:15」→ [{明,5},{暗,15}]；「5」→ [{'',5}]；讀唔到數字嘅項目就冇得撳 */
export function optionsOf(value: string): FanOption[] {
  return value
    .split('|')
    .map((part) => part.trim())
    .map((part) => {
      const m = part.match(/^(.*?)[:：]\s*(\d+)\s*$/);
      if (m) return { label: m[1].trim(), fan: Number(m[2]) };
      const n = part.match(/^(\d+)$/);
      return n ? { label: '', fan: Number(n[1]) } : null;
    })
    .filter((x): x is FanOption => x !== null);
}

const L = (s: string): FanItem => {
  const [main, note] = s.split('#');
  const i = main.lastIndexOf('=');
  return { name: main.slice(0, i).trim(), value: main.slice(i + 1).trim(), ...(note ? { note: note.trim() } : {}) };
};

