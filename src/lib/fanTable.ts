export function glossaryOf(name: string): string | undefined {
  const base = name.replace(/（.*?）|\(.*?\)/g, '').split(/[／/]/)[0].trim();
  return FAN_GLOSSARY[base] ?? FAN_GLOSSARY[name];
}
